// gatewayOwner is the ownerReference Istio puts on the Service it generates for a Gateway.
func gatewayOwner(apiVersion string) v1.OwnerReference {
	return v1.OwnerReference{APIVersion: apiVersion, Kind: "Gateway", Name: "public-akamai", UID: "gw-uid"}
}

// TestReconcileServiceSkipsGatewayServices verifies that a Service generated for a Gateway API
// Gateway is left alone even though it carries the Gateway's (copied) allowlist annotation:
// loadBalancerSourceRanges would apply at the load balancer, before the HTTPRoutes'
// AuthorizationPolicies, and drop every CIDR a route allows beyond the Gateway's.
func TestReconcileServiceSkipsGatewayServices(t *testing.T) {
	cases := []struct {
		name    string
		owners  []v1.OwnerReference
		labels  map[string]string
		managed bool
	}{
		{"generated by Istio for a Gateway (owner + label)", []v1.OwnerReference{gatewayOwner("gateway.networking.k8s.io/v1")}, map[string]string{gatewayNameLabel: "public-akamai"}, false},
		{"gateway-name label only", nil, map[string]string{gatewayNameLabel: "public-akamai"}, false},
		{"owned by Istio's classic Gateway (networking.istio.io)", []v1.OwnerReference{gatewayOwner("networking.istio.io/v1")}, nil, true},
		{"ordinary LoadBalancer Service", nil, nil, true},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			cidrs := &ipamv1alpha1.ClusterCIDRs{
				ObjectMeta: v1.ObjectMeta{Name: "akamai"},
				Status:     ipamv1alpha1.CIDRsStatus{CIDRs: []string{"23.0.0.0/12"}},
			}
			service := loadBalancerService(map[string]string{"ipam.adevinta.com/cluster-allowlist-group": "akamai"})
			service.OwnerReferences = tc.owners
			service.Labels = tc.labels
			k8sClient := fake.NewClientBuilder().WithScheme(extendedScheme).WithObjects(cidrs, service).Build()

			_, err := newServiceReconciler(t, k8sClient).Reconcile(context.Background(), reconcile.Request{NamespacedName: client.ObjectKeyFromObject(service)})
			require.NoError(t, err)

			got := &corev1.Service{}
			require.NoError(t, k8sClient.Get(context.Background(), client.ObjectKeyFromObject(service), got))
			if tc.managed {
				assert.Equal(t, []string{"23.0.0.0/12"}, got.Spec.LoadBalancerSourceRanges)
			} else {
				assert.Empty(t, got.Spec.LoadBalancerSourceRanges, "a Gateway's Service must not get loadBalancerSourceRanges")
			}
		})
	}
}

// TestLogAnnotationRemovalIgnoresGatewayServices verifies that no "stopped managing" warning is
// logged for a Gateway's Service, which was never managed (Istio removes the copied annotation when
// it is removed from the Gateway).
func TestLogAnnotationRemovalIgnoresGatewayServices(t *testing.T) {
	logs := captureLogs(t)
	annotated := loadBalancerService(map[string]string{"ipam.adevinta.com/cluster-allowlist-group": "akamai"})
	annotated.Labels = map[string]string{gatewayNameLabel: "public-akamai"}
	removed := annotated.DeepCopy()
	removed.Annotations = nil

	assert.True(t, logAnnotationRemoval("Service", "ipam.adevinta.com").Update(event.UpdateEvent{ObjectOld: annotated, ObjectNew: removed}))
	assert.NotContains(t, logs.String(), "allowlist annotation removed")
}
